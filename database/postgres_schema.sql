-- Gridlock Rescue PostgreSQL baseline. Run as Supabase schema owner/migration user.
-- Intentionally does NOT seed IDs or example users: real Railway exports must be imported intact.
-- All timestamp-without-time-zone values are UTC (MySQL exporter sets time_zone='+00:00').
BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(20) NOT NULL,
    email varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(5) NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_users_id_unsigned CHECK (user_id BETWEEN 1 AND 4294967295)
);
-- Enforce MySQL's case-insensitive semantics for ASCII usernames and email addresses.
-- These expression indexes reject case-only duplicates even under concurrent inserts.
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_ci ON public.users ((lower(username)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_ci ON public.users ((lower(email)));

CREATE TABLE IF NOT EXISTS public.levels (
    level_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_type varchar(7) NOT NULL DEFAULT 'sokoban' CHECK (game_type IN ('sokoban','sliding')),
    title varchar(60) NOT NULL,
    hint varchar(255),
    difficulty varchar(6) NOT NULL DEFAULT 'easy' CHECK (difficulty IN ('easy','medium','hard','expert')),
    sort_order bigint NOT NULL DEFAULT 1 CHECK (sort_order BETWEEN 0 AND 4294967295),
    grid_width smallint NOT NULL CHECK (grid_width BETWEEN 0 AND 255),
    grid_height smallint NOT NULL CHECK (grid_height BETWEEN 0 AND 255),
    layout text NOT NULL,
    par_moves bigint CHECK (par_moves BETWEEN 0 AND 4294967295),
    created_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_levels_id_unsigned CHECK (level_id BETWEEN 1 AND 4294967295)
);
CREATE INDEX IF NOT EXISTS idx_levels_order ON public.levels (sort_order, level_id);
CREATE INDEX IF NOT EXISTS idx_levels_game_order ON public.levels (game_type, sort_order, level_id);

CREATE TABLE IF NOT EXISTS public.user_progress (
    progress_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    level_id bigint NOT NULL,
    best_moves bigint NOT NULL CHECK (best_moves BETWEEN 0 AND 4294967295),
    completed_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_progress_id_unsigned CHECK (progress_id BETWEEN 1 AND 4294967295),
    CONSTRAINT uq_progress_user_level UNIQUE (user_id, level_id),
    CONSTRAINT fk_progress_user FOREIGN KEY (user_id) REFERENCES public.users(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_progress_level FOREIGN KEY (level_id) REFERENCES public.levels(level_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_progress_user ON public.user_progress (user_id);
CREATE INDEX IF NOT EXISTS idx_progress_level ON public.user_progress (level_id);

CREATE OR REPLACE FUNCTION public.gridlock_touch_progress_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF ROW(NEW.user_id, NEW.level_id, NEW.best_moves, NEW.completed_at)
     IS DISTINCT FROM ROW(OLD.user_id, OLD.level_id, OLD.best_moves, OLD.completed_at) THEN
    NEW.updated_at := CURRENT_TIMESTAMP AT TIME ZONE 'UTC';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_gridlock_progress_updated_at ON public.user_progress;
CREATE TRIGGER trg_gridlock_progress_updated_at
BEFORE UPDATE ON public.user_progress
FOR EACH ROW EXECUTE FUNCTION public.gridlock_touch_progress_updated_at();

-- Runtime PHP sessions: payload contains base64-encoded native PHP session serialization.
CREATE TABLE IF NOT EXISTS public.app_sessions (
    session_id varchar(128) PRIMARY KEY,
    payload text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_app_sessions_expires_at ON public.app_sessions (expires_at);

-- Explicit RLS and grants ensure no anon/authenticated Data API access.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.levels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.users, public.levels, public.user_progress, public.app_sessions FROM PUBLIC, anon, authenticated;
COMMIT;
